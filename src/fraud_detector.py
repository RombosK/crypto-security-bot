def _level_from_score(score: int) -> str:
    """Преобразует числовой скор в текстовую оценку уровня опасности."""
    if score < 20:
        return "Безопасно"
    if score < 50:
        return "Подозрительно"
    if score < 75:
        return "Опасно"
    return "Критично"


def analyze_message(text: str) -> AnalysisResult:
    """
    Анализирует текст сообщения на признаки мошенничества.

    Алгоритм:
    1. Текст приводится к нижнему регистру
    2. Проверяется каждый признак: если найдено ключевое слово — добавляется вес
    3. Веса суммируются и нормируются к 0-100
    4. Дополнительно проверяется совпадение с известными схемами

    Args:
        text: сообщение для анализа

    Returns:
        AnalysisResult с оценкой, признаками и рекомендацией
    """
    if not text or not text.strip():
        return AnalysisResult(
            score=0,
            level="Безопасно",
            found_signs=[],
            matched_schemes=[],
            recommendation="Сообщение пустое.",
        )

    lower_text = text.lower()
    found_signs: List[dict] = []
    total_weight = 0

    # --- Проверка признаков ---
    for sign in SIGNS:
        for kw in sign["keywords"]:
            if kw in lower_text:
                found_signs.append({
                    "description": sign["description"],
                    "weight": sign["weight"],
                })
                total_weight += sign["weight"]
                break  # считаем признак один раз

    # --- Нормировка ---
    # Максимальный возможный вес — сумма весов всех признаков,
    # но на практике 50 — порог «Опасно», 75 — «Критично».
    # Формула: min(100, total_weight * 100 / max_possible)
    # Используем простой подход: каждые 5 единиц веса = 10% скор.
    score = min(100, total_weight * 10)

    # --- Проверка схем ---
    matched_schemes: List[dict] = []
    for scheme in SCAM_SCHEMES:
        matched_kw = [kw for kw in scheme["keywords"] if kw in lower_text]
        if len(matched_kw) >= 2:  # минимум 2 совпадения для отнесения к схеме
            matched_schemes.append({
                "name": scheme["name"],
                "description": scheme["description"],
                "what_to_do": scheme["what_to_do"],
                "matched_keywords": matched_kw,
            })

    # --- Рекомендация ---
    level = _level_from_score(score)
    if score >= 75:
        recommendation = (
            "КРИТИЧНО: с очень высокой вероятностью это мошенничество!\n"
            "Не переводите деньги, не сообщайте коды и пароли.\n"
            "Если уже перевели деньги — немедленно позвоните в банк."
        )
    elif score >= 50:
        recommendation = (
            "ОПАСНО: много признаков мошенничества.\n"
            "Не действуйте под давлением, проверьте информацию самостоятельно.\n"
            "Не переводите деньги, пока не убедитесь в подлинности собеседника."
        )
    elif score >= 20:
        recommendation = (
            "ПОДОЗРИТЕЛЬНО: есть отдельные тревожные признаки.\n"
            "Будьте внимательны, не спешите действовать по инструкции из сообщения."
        )
    else:
        recommendation = "Явных признаков мошенничества не найдено, но сохраняйте бдительность."

    return AnalysisResult(
        score=score,
        level=level,
        found_signs=found_signs,
        matched_schemes=matched_schemes,
        recommendation=recommendation,
    )


def get_scheme_info(scheme_id: str) -> dict | None:
    """Возвращает информацию о схеме по её идентификатору."""
    for scheme in SCAM_SCHEMES:
        if scheme["id"] == scheme_id:
            return scheme
    return None


def list_schemes() -> list[dict]:
    """Возвращает список всех схем (без ключевых слов, только для отображения)."""
    return [
        {"id": s["id"], "name": s["name"], "description": s["description"]}
        for s in SCAM_SCHEMES
    ]